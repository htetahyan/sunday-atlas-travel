/**
 * content/image-registry.json — every image used site-wide.
 *
 * Entry: { key, source: { provider, id, pageUrl, author, license, licenseUrl },
 *          phash, cloudinary: { publicId, url, width, height }, uses: [{ type, slug, field }] }
 * `key` is the source key ("commons:<pageid>", "pexels:<id>", "unsplash:<id>") or
 * "cloudinary:<public_id>" when the original source is unknown.
 *
 * New images are rejected when the source key is already used, or when any used
 * image is within PHASH_MAX_DISTANCE bits (near-duplicate: crop, resize, re-encode).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { hamming } from "./phash.mjs";

export const REGISTRY_PATH = "content/image-registry.json";
export const PHASH_MAX_DISTANCE = Number(process.env.IMAGE_PHASH_MAX_DISTANCE || 6);

export function loadRegistry(path = REGISTRY_PATH) {
  if (!existsSync(path)) return { version: 1, images: [] };
  const data = JSON.parse(readFileSync(path, "utf8"));
  return { version: 1, ...data, images: data.images ?? [] };
}

export function saveRegistry(reg, path = REGISTRY_PATH) {
  const images = [...reg.images].sort((a, b) => a.key.localeCompare(b.key));
  for (const img of images)
    img.uses = [...new Map((img.uses ?? []).map((u) => [`${u.type}:${u.slug}:${u.field}`, u])).values()].sort((a, b) =>
      `${a.type}:${a.slug}:${a.field}`.localeCompare(`${b.type}:${b.slug}:${b.field}`),
    );
  writeFileSync(path, `${JSON.stringify({ version: 1, note: "Generated by scripts/lib/image-registry.mjs. Every image used site-wide; no source or near-duplicate (pHash) may be used twice.", images }, null, 2)}\n`);
}

/** Cloudinary public id from a delivery URL (without version and extension). */
export function cloudinaryPublicId(url) {
  const m = String(url ?? "").match(/res\.cloudinary\.com\/[^/]+\/image\/upload\/(?:[^/]*[,_][^/]*\/)*(?:v\d+\/)?(.+?)(?:\.[a-z0-9]{2,5})?$/i);
  return m ? m[1] : null;
}

export function findBySrc(reg, src) {
  return reg.images.find((i) => i.cloudinary?.url === src);
}

/**
 * Duplicate check for a candidate { key, phash }. Entries with no uses are
 * uploads reserved by a skipped post; they block nothing and may be reused by key.
 * `ignoreUse` lets a page keep its own current images when re-checked.
 */
export function duplicateOf(reg, { key, phash }, { maxDistance = PHASH_MAX_DISTANCE, ignoreUse } = {}) {
  for (const img of reg.images) {
    const uses = (img.uses ?? []).filter((u) => !ignoreUse || !(u.type === ignoreUse.type && u.slug === ignoreUse.slug));
    if (!uses.length) continue;
    if (key && img.key === key) return { entry: img, why: "same source", distance: 0 };
    const d = hamming(phash, img.phash);
    if (d <= maxDistance) return { entry: img, why: `near-duplicate (pHash distance ${d})`, distance: d };
  }
  return null;
}

/** Unused (reserved) upload for this source key, so a retry does not upload again. */
export function reservedFor(reg, key) {
  return reg.images.find((i) => i.key === key && !(i.uses ?? []).length && i.cloudinary?.url);
}

export function upsert(reg, entry) {
  const found = reg.images.find((i) => i.key === entry.key);
  if (found) {
    Object.assign(found, { ...entry, uses: [...(found.uses ?? []), ...(entry.uses ?? [])] });
    return found;
  }
  const e = { uses: [], ...entry };
  reg.images.push(e);
  return e;
}

export function addUse(reg, key, use) {
  const e = reg.images.find((i) => i.key === key);
  if (!e) throw new Error(`registry has no ${key}`);
  e.uses = [...(e.uses ?? []), use];
  return e;
}

/** Remove all uses of a page (e.g. before re-registering a post that was rewritten). */
export function clearUses(reg, type, slug) {
  for (const e of reg.images) e.uses = (e.uses ?? []).filter((u) => !(u.type === type && u.slug === slug));
}

/** Groups of entries in use that are exact (same key) or near duplicates of each other. */
export function duplicateGroups(reg, maxDistance = PHASH_MAX_DISTANCE) {
  const used = reg.images.filter((i) => (i.uses ?? []).length);
  const groups = [];
  const seen = new Set();
  for (let a = 0; a < used.length; a += 1) {
    if (seen.has(a)) continue;
    const g = [used[a]];
    for (let b = a + 1; b < used.length; b += 1) {
      if (seen.has(b)) continue;
      const sameSource = used[a].source?.pageUrl && used[a].source.pageUrl === used[b].source?.pageUrl;
      const d = hamming(used[a].phash, used[b].phash);
      if (sameSource || d <= maxDistance) {
        g.push({ ...used[b], distance: sameSource ? 0 : d });
        seen.add(b);
      }
    }
    if (g.length > 1) groups.push(g);
  }
  return groups;
}

