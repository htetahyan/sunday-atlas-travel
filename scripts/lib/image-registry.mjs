import { readdirSync } from "node:fs";

const TYPES = { blog: "content/blog", destination: "content/destinations", package: "content/packages" };

/** Every image reference in blog posts, destinations and packages. */
export function collectSiteImages(root = ".") {
  const out = [];
  for (const [type, dir] of Object.entries(TYPES)) {
    const path = `${root}/${dir}`;
    if (!existsSync(path)) continue;
    for (const f of readdirSync(path).filter((n) => n.endsWith(".json")).sort()) {
      const doc = JSON.parse(readFileSync(`${path}/${f}`, "utf8"));
      const slug = doc.slug || f.replace(/\.json$/, "");
      const push = (img, field, alt) => {
        if (img?.src) out.push({ src: img.src, width: img.width, height: img.height, alt: alt ?? img.alt, use: { type, slug, field } });
      };
      if (type === "blog") {
        push(doc.heroImage, "heroImage");
        (doc.sections ?? []).forEach((s, i) => push(s.image, `sections.${s.id || i}.image`));
      } else {
        push(doc.image, "image");
        (doc.gallery ?? []).forEach((g, i) => push(g.image, `gallery.${i}`, g.alt));
        (doc.itinerary ?? []).forEach((d, i) => push(d.image?.image ?? d.image, `itinerary.${d.day ?? i + 1}.image`, d.image?.alt));
      }
    }
  }
  return out;
}

/** Source of an existing image: CREDITS.md row, else a Pexels id in the Cloudinary file name. */
export function sourceForExisting(src, credits = new Map()) {
  const c = credits.get(src);
  if (c) return c;
  const pid = cloudinaryPublicId(src) ?? src;
  const m = pid.match(/-(\d{6,9})(?:_[a-z0-9]{6})?$/);
  if (m) return { key: `pexels:${m[1]}`, source: { provider: "pexels", id: m[1], pageUrl: `https://www.pexels.com/photo/${m[1]}/`, license: "Pexels License", licenseUrl: "https://www.pexels.com/license/", inferred: true } };
  return { key: `cloudinary:${pid}`, source: { provider: "unknown" } };
}

/** Parse public/images/CREDITS.md into Map(cloudinaryUrl → { key, source }). */
export function parseCredits(text) {
  const map = new Map();
  for (const line of String(text ?? "").split("\n")) {
    if (!line.startsWith("| `")) continue;
    const cols = line.split("|").map((c) => c.trim());
    const [, , place, author, page, , cld] = cols;
    const id = (page.match(/-(\d+)\/?$/) || [])[1];
    if (!cld?.startsWith("https://res.cloudinary.com") || !id) continue;
    map.set(cld, { key: `pexels:${id}`, source: { provider: "pexels", id, pageUrl: page, author, license: "Pexels License", licenseUrl: "https://www.pexels.com/license/", title: place.slice(0, 120) } });
  }
  return map;
}
